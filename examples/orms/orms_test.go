// TestGORM checks that a GORM transaction saves an order and its task
// together, and that a commit that fails saves neither.
func TestGORM(t *testing.T) {
	t.Parallel()
	pool, client := testShop(t)
	db, err := openGORM(pool)
	if err != nil {
		t.Fatal(err)
	}
	checkOrders(t, pool, client, func(ctx context.Context, email string) error {
		return placeOrderGORM(ctx, db, client, email)
	})
}

// TestEnt checks the same with an ent transaction.
func TestEnt(t *testing.T) {
	t.Parallel()
	pool, client := testShop(t)
	db := openEnt(pool)
	t.Cleanup(func() { _ = db.Close() })
	checkOrders(t, pool, client, func(ctx context.Context, email string) error {
		return placeOrderEnt(ctx, db, client, email)
	})
}

// checkOrders places two orders with the same email. The second fails at its
// commit, after its task was enqueued: one order and one task remain.
func checkOrders(t *testing.T, pool *pgxpool.Pool, client *taskmill.Client, placeOrder func(context.Context, string) error) {
	t.Helper()
	if err := placeOrder(t.Context(), "ada@example.com"); err != nil {
		t.Fatal(err)
	}
	if err := placeOrder(t.Context(), "ada@example.com"); err == nil {
		t.Fatal("the second order with the same email committed")
	}

	var orderID int64
	if err := pool.QueryRow(t.Context(), "SELECT id FROM orders").Scan(&orderID); err != nil {
		t.Fatal(err) // also when there are two orders
	}
	tasks := taskmilltest.Enqueued[SendReceipt](t, client)
	if len(tasks) != 1 || tasks[0].Args.OrderID != orderID {
		t.Fatalf("got %d tasks, want 1 for order %d: %+v", len(tasks), orderID, tasks)
	}
}

// testShop returns a pool and a client in a schema of the test's own, which
// also holds the orders table: the ORMs name no schema, so the pool's search
// path puts the table there. The table takes one order per email, checked at
// the commit, so that a commit can fail after the enqueue.
func testShop(t *testing.T) (*pgxpool.Pool, *taskmill.Client) {
	t.Helper()
	schema := testdb.Schema(t, testdb.Pool(t))
	// A pooler in transaction mode refuses a search path: connect without it.
	cfg, err := pgxpool.ParseConfig(testdb.DirectURL(t))
	if err != nil {
		t.Fatal(err)
	}
	cfg.ConnConfig.RuntimeParams["search_path"] = schema
	pool, err := pgxpool.NewWithConfig(t.Context(), cfg)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(pool.Close)

	if err := taskmill.Migrate(t.Context(), pool, &taskmill.MigrateConfig{Schema: schema}); err != nil {
		t.Fatal(err)
	}
	_, err = pool.Exec(t.Context(), `CREATE TABLE orders (
		id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
		email text NOT NULL UNIQUE DEFERRABLE INITIALLY DEFERRED
	)`)
	if err != nil {
		t.Fatal(err)
	}
	client, err := taskmill.NewClient(t.Context(), pool, &taskmill.ClientConfig{Schema: schema})
	if err != nil {
		t.Fatal(err)
	}
	return pool, client
}
